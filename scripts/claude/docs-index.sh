# Generates docs/specs/INDEX.md (one line per .feature: path, Feature title,
# scenario count) and docs/sessions/INDEX.md (one line per session: file,
# first heading). Generated, never edited by hand: docs/sessions/ is
# append-only. Idempotent: a second run changes nothing.
set -euo pipefail

ROOT="${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
cd "$ROOT"
export LC_ALL=C.UTF-8

header() { # header <title> <generator note>
  printf '<!-- SPDX-License-Identifier: AGPL-3.0-only -->\n'
  printf '<!-- Copyright 2026 Artur Abalov -->\n\n'
  printf '# %s\n\nGenerated by `scripts/claude/docs-index.sh`; do not edit.\n\n' "$1"
}

specs() {
  header "Specs index"
  echo '| File | Feature | Scenarios |'
  echo '|---|---|---|'
  find docs/specs -name '*.feature' | sort | while read -r f; do
    title="$(grep -m1 -E '^[[:space:]]*(Feature|Функционал|Функция):' "$f" | sed -E 's/^[[:space:]]*[^:]+:[[:space:]]*//; s/\|/\\|/g' || true)"
    count="$(grep -cE '^[[:space:]]*(Scenario|Scenario Outline|Сценарий|Структура сценария):' "$f" || true)"
    echo "| ${f#docs/specs/} | $title | $count |"
  done
}

sessions() {
  header "Sessions index"
  echo '| Session | Title |'
  echo '|---|---|'
  find docs/sessions -maxdepth 1 -name '*.md' ! -name INDEX.md | sort | while read -r f; do
    title="$(grep -m1 -E '^# ' "$f" | sed -E 's/^# //; s/\|/\\|/g' || true)"
    echo "| $(basename "$f") | $title |"
  done
}

specs >docs/specs/INDEX.md
sessions >docs/sessions/INDEX.md
